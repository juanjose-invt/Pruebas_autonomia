const KEY = 'tirada.lang';
let lang = 'es';
try { const saved = localStorage.getItem(KEY); if (saved === 'en' || saved === 'es') lang = saved; } catch { /* almacenamiento bloqueado */ }

export function getLang() { return lang; }
export function setLang(l) {
  lang = l === 'en' ? 'en' : 'es';
  try { localStorage.setItem(KEY, lang); } catch { /* sin persistencia */ }
  document.documentElement.lang = lang;
}
export function locale() { return lang === 'en' ? 'en-GB' : 'es-ES'; }

export function t(key, vars) {
  let s = STR[lang][key] ?? STR.es[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  root.querySelectorAll('[data-i18n-ph]').forEach((el) => { el.setAttribute('placeholder', t(el.dataset.i18nPh)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
}

// ---------- formatos ----------
const cache = new Map();
function nf(opts) {
  const k = locale() + JSON.stringify(opts);
  let f = cache.get(k);
  if (!f) { f = new Intl.NumberFormat(locale(), opts); cache.set(k, f); }
  return f;
}

function withUnit(s, unit) {
  if (!unit) return s;
  if (unit === '%') return lang === 'es' ? `${s} %` : `${s}%`;
  if (lang === 'es') return `${s} ${unit}`;
  return /^-/.test(s) ? `-${unit}${s.slice(1)}` : `${unit}${s}`;
}

// Número legible: decimales según magnitud.
export function fmtNum(v, unit = '', opts = {}) {
  if (v == null || Number.isNaN(v)) return '—';
  const a = Math.abs(v);
  const maxF = opts.maxFrac ?? (a >= 1000 ? 0 : a >= 100 ? 1 : a >= 1 ? 2 : 3);
  const minF = opts.minFrac ?? 0;
  return withUnit(nf({ maximumFractionDigits: maxF, minimumFractionDigits: Math.min(minF, maxF) }).format(v), unit);
}

// Para ejes: compacto cuando el número es grande.
export function fmtAxis(v, unit = '', step = 1) {
  const a = Math.abs(v);
  if (a >= 10000) return withUnit(nf({ notation: 'compact', maximumFractionDigits: a >= 1e6 && step < a / 10 ? 1 : 1 }).format(v), unit);
  const frac = step >= 1 ? 0 : Math.min(4, Math.ceil(-Math.log10(step)));
  return withUnit(nf({ maximumFractionDigits: frac, minimumFractionDigits: frac }).format(v), unit);
}

export function fmtInt(v) { return nf({ maximumFractionDigits: 0 }).format(v); }

const dcache = new Map();
function df(opts) {
  const k = locale() + JSON.stringify(opts);
  let f = dcache.get(k);
  if (!f) { f = new Intl.DateTimeFormat(locale(), { timeZone: 'UTC', ...opts }); dcache.set(k, f); }
  return f;
}

export function fmtDate(t, withTime = false) {
  if (t == null || Number.isNaN(t)) return '—';
  return df(withTime ? { day: '2-digit', month: '2-digit', year: 'numeric', hour: '2-digit', minute: '2-digit' } : { day: '2-digit', month: '2-digit', year: 'numeric' }).format(t);
}

// Rótulo de un periodo agrupado.
export function fmtBucket(t, bucket, short = false) {
  const d = new Date(t);
  switch (bucket) {
    case 'year': return String(d.getUTCFullYear());
    case 'quarter': return `${lang === 'es' ? 'T' : 'Q'}${Math.floor(d.getUTCMonth() / 3) + 1} ${d.getUTCFullYear()}`;
    case 'month': return df(short ? { month: 'short', year: '2-digit' } : { month: 'long', year: 'numeric' }).format(t);
    case 'week': return (lang === 'es' ? 'sem. ' : 'wk ') + df({ day: 'numeric', month: 'short', ...(short ? {} : { year: 'numeric' }) }).format(t);
    default: return df(short ? { day: 'numeric', month: 'short' } : { day: 'numeric', month: 'short', year: 'numeric' }).format(t);
  }
}

export function fmtBytes(b) {
  if (b < 1024 * 1024) return `${fmtNum(b / 1024, '', { maxFrac: 0 })} KB`;
  return `${fmtNum(b / 1024 / 1024, '', { maxFrac: 1 })} MB`;
}
