let lang = 'es';
export const getLang = () => lang;
export function setLang(l) { lang = l === 'en' ? 'en' : 'es'; document.documentElement.lang = lang; }
export function t(key, ...args) {
  const row = S[key];
  if (!row) return key;
  let s = row[lang === 'en' ? 1 : 0];
  args.forEach((a, i) => { s = s.replace('{' + i + '}', a); });
  return s;
}
export const tr = (obj) => (obj ? obj[lang] || obj.es : '');
